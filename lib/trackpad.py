def die(msg, code=1):
    print(msg, file=sys.stderr)
    raise SystemExit(code)


def home_dir():
    return pwd.getpwuid(os.geteuid()).pw_dir


def _ok_component(name):
    return bool(SAFE_COMPONENT.fullmatch(name)) and name not in (".", "..")


def open_dir_chain(parts, leaf_private=True, create=True):
    if not parts or not all(_ok_component(p) for p in parts):
        raise PermissionError("refusing directory chain")
    fd = os.open(home_dir(), os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC)
    try:
        for i, name in enumerate(parts):
            last = i == len(parts) - 1
            try:
                nfd = os.open(
                    name,
                    os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC,
                    dir_fd=fd,
                )
            except FileNotFoundError:
                if not create:
                    raise
                mode = 0o700 if (last and leaf_private) else 0o755
                try:
                    os.mkdir(name, mode, dir_fd=fd)
                except FileExistsError:
                    pass
                nfd = os.open(
                    name,
                    os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC,
                    dir_fd=fd,
                )
            os.close(fd)
            fd = nfd
            st = os.fstat(fd)
            if not stat.S_ISDIR(st.st_mode) or st.st_uid != os.geteuid():
                raise PermissionError(f"untrusted directory component {name}")
            if last and leaf_private and st.st_mode & 0o077:
                os.fchmod(fd, 0o700)
        return fd
    except BaseException:
        os.close(fd)
        raise


def read_bounded(dirfd, name, max_bytes, require_private=True):
    try:
        fd = os.open(
            name,
            os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC,
            dir_fd=dirfd,
        )
    except FileNotFoundError:
        return None
    try:
        st = os.fstat(fd)
        if (
            not stat.S_ISREG(st.st_mode)
            or st.st_uid != os.geteuid()
            or st.st_nlink != 1
            or st.st_size > max_bytes
        ):
            raise PermissionError("refusing state file")
        if require_private and st.st_mode & 0o077:
            os.fchmod(fd, 0o600)
        elif (not require_private) and st.st_mode & 0o002:
            raise PermissionError("refusing world-writable file")
        os.set_blocking(fd, True)
        data = b""
        while len(data) <= max_bytes:
            chunk = os.read(fd, min(65536, max_bytes + 1 - len(data)))
            if not chunk:
                break
            data += chunk
        if len(data) > max_bytes:
            raise PermissionError("state file grew past the limit")
        return data
    finally:
        os.close(fd)


def write_atomic(dirfd, name, data, mode=0o600):
    if len(data) > MAX_HYPR:
        raise ValueError("payload too large")
    tmp = f".{name}.{secrets.token_hex(8)}.tmp"
    fd = os.open(
        tmp,
        os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
        mode,
        dir_fd=dirfd,
    )
    try:
        os.fchmod(fd, mode)
        view = memoryview(data)
        while view:
            n = os.write(fd, view)
            view = view[n:]
        os.fsync(fd)
        os.rename(tmp, name, src_dir_fd=dirfd, dst_dir_fd=dirfd)
        os.fsync(dirfd)
    except BaseException:
        try:
            os.unlink(tmp, dir_fd=dirfd)
        except OSError:
            pass
        raise
    finally:
        os.close(fd)


def unlink_named(dirfd, name):
    try:
        st = os.lstat(name, dir_fd=dirfd)
    except FileNotFoundError:
        return False
    if not stat.S_ISREG(st.st_mode) or st.st_uid != os.geteuid():
        raise PermissionError(f"refusing to delete {name}")
    os.unlink(name, dir_fd=dirfd)
    return True


def repair_state_dir(dirfd):
    try:
        names = os.listdir(f"/proc/self/fd/{dirfd}")
    except OSError:
        return
    for name in names:
        if not _ok_component(name):
            continue
        try:
            st = os.lstat(name, dir_fd=dirfd)
        except OSError:
            continue
        if stat.S_ISREG(st.st_mode):
            if st.st_uid == os.geteuid() and st.st_mode & 0o077:
                try:
                    fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=dirfd)
                    try:
                        os.fchmod(fd, 0o600)
                    finally:
                        os.close(fd)
                except OSError:
                    pass
            continue
        if stat.S_ISDIR(st.st_mode):
            continue
        try:
            os.unlink(name, dir_fd=dirfd)
        except OSError:
            pass


