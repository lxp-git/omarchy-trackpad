def _child_env():
    keep = (
        "HOME",
        "USER",
        "LOGNAME",
        "XDG_RUNTIME_DIR",
        "XDG_CONFIG_HOME",
        "XDG_STATE_HOME",
        "WAYLAND_DISPLAY",
        "HYPRLAND_INSTANCE_SIGNATURE",
        "DBUS_SESSION_BUS_ADDRESS",
    )
    env = {k: os.environ[k] for k in keep if os.environ.get(k)}
    env["PATH"] = "/usr/bin:/bin"
    env["LC_ALL"] = "C.UTF-8"
    return env


def _kill_group(proc, sig):
    try:
        os.killpg(proc.pid, sig)
    except (ProcessLookupError, PermissionError, OSError):
        pass


def bounded_cmd(argv, max_bytes=MAX_CMD, timeout=2):
    if not argv or not os.path.isabs(argv[0]):
        raise ValueError("absolute executable required")
    proc = subprocess.Popen(
        argv,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
        env=_child_env(),
    )
    deadline = time.monotonic() + timeout
    out = bytearray()
    fd = proc.stdout.fileno()
    try:
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise subprocess.TimeoutExpired(argv, timeout)
            ready, _, _ = select.select([proc.stdout], [], [], remaining)
            if not ready:
                raise subprocess.TimeoutExpired(argv, timeout)
            chunk = os.read(fd, min(65536, max_bytes + 1 - len(out)))
            if not chunk:
                break
            out += chunk
            if len(out) > max_bytes:
                _kill_group(proc, signal.SIGTERM)
                try:
                    proc.wait(timeout=2)
                except subprocess.TimeoutExpired:
                    _kill_group(proc, signal.SIGKILL)
                    proc.wait(timeout=1)
                raise ValueError("command output too large")
        rc = proc.wait(timeout=max(0.1, deadline - time.monotonic()))
    except subprocess.TimeoutExpired:
        _kill_group(proc, signal.SIGTERM)
        try:
            proc.wait(timeout=2)
        except subprocess.TimeoutExpired:
            _kill_group(proc, signal.SIGKILL)
            proc.wait(timeout=1)
        raise
    if rc != 0:
        raise subprocess.CalledProcessError(rc, argv)
    return bytes(out)


