def ioc(direction, type_, nr, size):
    return (
        (direction << IOC_DIRSHIFT)
        | (ord(type_) << IOC_TYPESHIFT)
        | (nr << IOC_NRSHIFT)
        | (size << IOC_SIZESHIFT)
    )


def clip_text(value, n=MAX_NAME):
    out = []
    for ch in str(value or ""):
        code = ord(ch)
        if ch in "<>&" or code < 32 or 0x7F <= code <= 0x9F:
            continue
        if ch.isprintable() or ch == " ":
            out.append(ch)
        if len(out) >= n:
            break
    return "".join(out)


def default_state():
    out = {key: True for key in KEYS}
    out["scrollFactor"] = SCROLL_DEFAULT
    return out


def coerce_scroll_factor(value):
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, int):
        n = float(value)
    elif isinstance(value, float):
        n = value
    else:
        text = str(value).strip()
        if len(text) > 8 or not SCROLL_TEXT.fullmatch(text):
            return None
        n = float(text)
    if not math.isfinite(n):
        return None
    n = round(n, 2)
    if n < SCROLL_MIN or n > SCROLL_MAX:
        return None
    return n


def parse_scroll_factor(value):
    n = coerce_scroll_factor(value)
    if n is None:
        die("scroll factor must be 0.10..2.00")
    return n


def load_json_file(dirfd, name, max_bytes=MAX_STATE):
    raw = read_bounded(dirfd, name, max_bytes)
    if raw is None:
        return None
    try:
        data, _ = json.JSONDecoder().raw_decode(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def load_state(dirfd):
    data = load_json_file(dirfd, "features.json")
    if data is not None:
        out = default_state()
        for key in KEYS:
            if key in data:
                out[key] = data[key] is True
        factor = coerce_scroll_factor(data.get("scrollFactor"))
        if factor is not None:
            out["scrollFactor"] = factor
        return out
    raw = read_bounded(dirfd, "enabled", MAX_STATE)
    if raw is not None:
        value = raw.decode("utf-8", "replace").strip() != "0"
        out = {key: value for key in KEYS}
        out["scrollFactor"] = SCROLL_DEFAULT
        return out
    return default_state()


def save_state(dirfd, state):
    payload = {key: bool(state[key]) for key in KEYS}
    payload["scrollFactor"] = parse_scroll_factor(state.get("scrollFactor", SCROLL_DEFAULT))
    write_atomic(dirfd, "features.json", (json.dumps(payload, indent=2) + "\n").encode())
    return payload


